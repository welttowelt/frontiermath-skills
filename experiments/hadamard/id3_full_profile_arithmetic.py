#!/usr/bin/env python3
"""Dependency-free arithmetic kernel for the ID3 full-profile search.

This module reconstructs the order-three multiplier action on Z/333Z, the
9-by-13 CRT grid, both prescribed compression axes, and exact periodic
autocorrelations.  It deliberately does not import the LP(333) artifact.
"""

from __future__ import annotations

from collections import Counter
from math import gcd
from typing import Iterable, Sequence

from py39_compat import int_bit_count


LENGTH = 333
MOD9 = 9
MOD37 = 37
MULTIPLIER_GENERATOR = 10
TARGET_COMBINED_PAF = -2


def cyclic_subgroup(generator: int, modulus: int) -> tuple[int, ...]:
    """Return the multiplicative subgroup generated by ``generator``."""

    if gcd(generator, modulus) != 1:
        raise ValueError("generator is not a unit")
    values: list[int] = []
    current = 1
    while current not in values:
        values.append(current)
        current = current * generator % modulus
    if current != 1:
        raise ValueError("generated powers did not close at the identity")
    return tuple(sorted(values))


def multiplication_orbits(
    subgroup: Iterable[int], modulus: int
) -> list[list[int]]:
    """Reconstruct the orbits of a multiplicative subgroup on Z/modulus."""

    group = tuple(sorted(set(subgroup)))
    unseen = set(range(modulus))
    orbits: list[list[int]] = []
    while unseen:
        seed = min(unseen)
        orbit = sorted({multiplier * seed % modulus for multiplier in group})
        unseen.difference_update(orbit)
        orbits.append(orbit)
    orbits.sort(key=lambda orbit: (len(orbit), orbit[0]))
    validate_orbit_partition(orbits, group, modulus)
    return orbits


def validate_orbit_partition(
    orbits: Sequence[Sequence[int]],
    subgroup: Iterable[int],
    modulus: int,
) -> None:
    """Reject incomplete, overlapping, or non-invariant orbit partitions."""

    group = tuple(sorted(set(subgroup)))
    if not group or 1 not in group:
        raise ValueError("subgroup must be nonempty and contain the identity")
    flattened: list[int] = []
    for orbit_index, orbit_values in enumerate(orbits):
        orbit = set(orbit_values)
        if not orbit:
            raise ValueError(f"orbit {orbit_index} is empty")
        if len(orbit) != len(orbit_values):
            raise ValueError(f"orbit {orbit_index} contains duplicates")
        if any(value < 0 or value >= modulus for value in orbit):
            raise ValueError(f"orbit {orbit_index} has an out-of-range residue")
        seed = next(iter(orbit))
        expected = {multiplier * seed % modulus for multiplier in group}
        if orbit != expected:
            raise ValueError(
                f"orbit {orbit_index} is not the subgroup orbit of {seed}"
            )
        flattened.extend(orbit_values)
    if len(flattened) != len(set(flattened)):
        raise ValueError("orbit partition overlaps")
    if set(flattened) != set(range(modulus)):
        raise ValueError("orbit partition does not cover the residue ring")


def orbit_signature(orbits: Sequence[Sequence[int]]) -> dict[int, int]:
    """Return ``orbit size -> multiplicity``."""

    return dict(sorted(Counter(map(len, orbits)).items()))


def crt_pair_to_index(residue9: int, residue37: int) -> int:
    """Map a pair in Z/9Z x Z/37Z to its unique residue in Z/333Z."""

    if not 0 <= residue9 < MOD9 or not 0 <= residue37 < MOD37:
        raise ValueError("CRT residue is out of range")
    term9 = residue9 * MOD37 * pow(MOD37, -1, MOD9)
    term37 = residue37 * MOD9 * pow(MOD9, -1, MOD37)
    result = (term9 + term37) % LENGTH
    if result % MOD9 != residue9 or result % MOD37 != residue37:
        raise AssertionError("CRT reconstruction failed")
    return result


def k37_orbits() -> list[list[int]]:
    """Return the singleton and twelve order-three orbits on Z/37Z."""

    subgroup = cyclic_subgroup(MULTIPLIER_GENERATOR % MOD37, MOD37)
    return multiplication_orbits(subgroup, MOD37)


def crt_grid_orbits() -> list[list[int]]:
    """Construct the 9-by-13 CRT cells as ID3 orbits in row-major order."""

    columns = k37_orbits()
    cells = [
        sorted(crt_pair_to_index(row, residue) for residue in column)
        for row in range(MOD9)
        for column in columns
    ]
    subgroup = cyclic_subgroup(MULTIPLIER_GENERATOR, LENGTH)
    validate_orbit_partition(cells, subgroup, LENGTH)
    return cells


def validate_crt_grid_against_orbits(
    orbits: Sequence[Sequence[int]],
) -> None:
    """Check that independently generated CRT cells and multiplier orbits agree."""

    expected = {frozenset(orbit) for orbit in crt_grid_orbits()}
    actual = {frozenset(orbit) for orbit in orbits}
    if actual != expected:
        raise ValueError("CRT grid and multiplier-orbit partitions disagree")


def validate_sign_table(table: Sequence[Sequence[int]]) -> None:
    if len(table) != MOD9:
        raise ValueError("sign table must have nine rows")
    for row_index, row in enumerate(table):
        if len(row) != 13:
            raise ValueError(f"sign-table row {row_index} must have 13 columns")
        if any(value not in (-1, 1) for value in row):
            raise ValueError(f"sign-table row {row_index} is not +/-1")


def sign_table_to_sequence(table: Sequence[Sequence[int]]) -> list[int]:
    """Lift a 9-by-13 sign table to a length-333 invariant sequence."""

    validate_sign_table(table)
    columns = k37_orbits()
    column_of = {
        residue: column_index
        for column_index, orbit in enumerate(columns)
        for residue in orbit
    }
    sequence = [0] * LENGTH
    for residue9 in range(MOD9):
        for residue37 in range(MOD37):
            index = crt_pair_to_index(residue9, residue37)
            sequence[index] = table[residue9][column_of[residue37]]
    if any(value not in (-1, 1) for value in sequence):
        raise AssertionError("CRT lift left an unassigned sequence entry")
    return sequence


def sequence_to_sign_table(sequence: Sequence[int]) -> list[list[int]]:
    """Decode an invariant sequence into its 9-by-13 CRT sign table."""

    if len(sequence) != LENGTH:
        raise ValueError("sequence must have length 333")
    if any(value not in (-1, 1) for value in sequence):
        raise ValueError("sequence is not +/-1")
    table: list[list[int]] = []
    for residue9 in range(MOD9):
        row: list[int] = []
        for orbit in k37_orbits():
            values = {
                sequence[crt_pair_to_index(residue9, residue37)]
                for residue37 in orbit
            }
            if len(values) != 1:
                raise ValueError(
                    f"sequence is not invariant in CRT row {residue9}"
                )
            row.append(next(iter(values)))
        table.append(row)
    return table


def orbit_values_to_sequence(
    orbits: Sequence[Sequence[int]], values: Sequence[int]
) -> list[int]:
    if len(orbits) != len(values):
        raise ValueError("orbit/value length mismatch")
    if any(value not in (-1, 1) for value in values):
        raise ValueError("orbit values are not +/-1")
    sequence = [0] * LENGTH
    for orbit, value in zip(orbits, values):
        for position in orbit:
            sequence[position] = value
    if any(value not in (-1, 1) for value in sequence):
        raise ValueError("orbits did not assign every sequence position")
    return sequence


def orbit_values_from_sequence(
    orbits: Sequence[Sequence[int]], sequence: Sequence[int]
) -> list[int]:
    if len(sequence) != LENGTH:
        raise ValueError("sequence must have length 333")
    values: list[int] = []
    for orbit_index, orbit in enumerate(orbits):
        observed = {sequence[position] for position in orbit}
        if len(observed) != 1:
            raise ValueError(
                f"sequence is not constant on multiplier orbit {orbit_index}"
            )
        value = next(iter(observed))
        if value not in (-1, 1):
            raise ValueError("sequence is not +/-1")
        values.append(value)
    return values


def compress_residue_classes(
    sequence: Sequence[int], modulus: int
) -> list[int]:
    """Sum sequence entries by their residue modulo ``modulus``."""

    if len(sequence) % modulus:
        raise ValueError("compression modulus does not divide the sequence")
    compressed = [0] * modulus
    for index, value in enumerate(sequence):
        compressed[index % modulus] += value
    return compressed


def legendre_symbol(value: int, prime: int = MOD37) -> int:
    residue = value % prime
    if residue == 0:
        return 0
    criterion = pow(residue, (prime - 1) // 2, prime)
    if criterion == 1:
        return 1
    if criterion == prime - 1:
        return -1
    raise ValueError("Euler criterion returned an unexpected residue")


def prescribed_q2_pair() -> tuple[list[int], list[int]]:
    a = [1] + [3 * legendre_symbol(index) for index in range(1, MOD37)]
    b = [1] + [-value for value in a[1:]]
    return a, b


def periodic_autocorrelation(sequence: Sequence[int], shift: int) -> int:
    length = len(sequence)
    return sum(
        sequence[index] * sequence[(index + shift) % length]
        for index in range(length)
    )


def periodic_autocorrelations_naive(sequence: Sequence[int]) -> list[int]:
    if any(value not in (-1, 1) for value in sequence):
        raise ValueError("sequence is not +/-1")
    return [
        periodic_autocorrelation(sequence, shift)
        for shift in range(len(sequence))
    ]


def periodic_autocorrelations_bitset(sequence: Sequence[int]) -> list[int]:
    """Compute every PAF exactly via cyclic Hamming distances."""

    length = len(sequence)
    if not length or any(value not in (-1, 1) for value in sequence):
        raise ValueError("sequence must be a nonempty +/-1 vector")
    mask = 0
    for index, value in enumerate(sequence):
        if value == -1:
            mask |= 1 << index
    low_mask = (1 << length) - 1
    profile: list[int] = []
    for shift in range(length):
        if shift == 0:
            rotated = mask
        else:
            rotated = (
                (mask >> shift) | (mask << (length - shift))
            ) & low_mask
        disagreements = int_bit_count(mask ^ rotated)
        profile.append(length - 2 * disagreements)
    return profile


def combined_paf_profile(
    first: Sequence[int], second: Sequence[int]
) -> list[int]:
    if len(first) != len(second):
        raise ValueError("sequence lengths differ")
    first_paf = periodic_autocorrelations_bitset(first)
    second_paf = periodic_autocorrelations_bitset(second)
    return [
        first_value + second_value
        for first_value, second_value in zip(first_paf, second_paf)
    ]
